let currentLang = localStorage.getItem("lang") || "en";
window.currentLang = currentLang;

function t(key) {
  return translations[currentLang]?.[key] || translations["en"]?.[key] || key;
}
window.t = t;

function applyTranslations(lang) {
  currentLang = lang;
  window.currentLang = lang;

  // data-i18n elements
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const val = translations[lang]?.[key] || translations["en"]?.[key];
    if (val) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = val;
      } else {
        el.textContent = val;
      }
    }
  });

  // Language switcher active state
  document.querySelectorAll(".lang-switcher .lang").forEach((el) => {
    el.classList.toggle("active", el.getAttribute("data-lang") === lang);
  });

  localStorage.setItem("lang", lang);
}

function switchLang(lang) {
  applyTranslations(lang);
  document.documentElement.lang = lang === "sq" ? "sq" : "en";
  // Re-render dynamic content
  if (typeof loadVillas === "function") loadVillas();
  if (typeof loadVillaDetails === "function") loadVillaDetails();
}

document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem("lang") || "en";
  applyTranslations(savedLang);
  document.documentElement.lang = savedLang === "sq" ? "sq" : "en";

  document.querySelectorAll(".lang-switcher .lang").forEach((el) => {
    el.addEventListener("click", () => {
      const lang = el.getAttribute("data-lang");
      switchLang(lang);
    });
  });
});
